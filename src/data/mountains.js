// 높이만으로 정하기 어려운 산은 직접 지정
const LEVEL_OVERRIDE = {
  "팔봉산(홍천)": "중급", // 낮지만 암릉 로프 구간
  월출산: "고급", // 경사가 급하고 암릉이 김
};

// 레벨별 메인 추천 산 (접근성이 좋고 유명한 산 위주)
const FEATURED = {
  초급: ["인왕산", "마니산(강화도)", "용봉산(홍성)"],
  중급: ["북한산", "도봉산", "관악산"],
  고급: ["설악산", "지리산 천왕봉", "한라산"],
};

function getLevel(name, height) {
  if (LEVEL_OVERRIDE[name]) return LEVEL_OVERRIDE[name];
  if (height < 500) return "초급";
  if (height < 1000) return "중급";
  return "고급";
}

// 소재지 첫 단어로 권역 나누기
function getArea(region) {
  const first = region.split(/[ ,]/)[0];
  if (["서울", "경기", "인천"].includes(first)) return "수도권";
  if (first === "강원") return "강원";
  if (["충북", "충남", "대전"].includes(first)) return "충청";
  if (["전북", "전남", "광주"].includes(first)) return "전라";
  if (["경북", "경남", "대구", "부산", "울산"].includes(first)) return "경상";
  return "제주";
}

export const AREAS = ["수도권", "강원", "충청", "전라", "경상", "제주"];

// series: "100" = 블랙야크 명산100, "100+" = 명산100+
// id는 "100-1", "plus-1"처럼 목록 + 번호로 만듭니다.
function toMountain([name, height, region, lat, lng, desc], i, series) {
  const level = getLevel(name, height);
  return {
    id: series === "100" ? `100-${i + 1}` : `plus-${i + 1}`,
    series,
    seriesLabel: series === "100" ? "명산100" : "명산100+",
    name,
    height,
    elevation: `${height.toLocaleString()}m`,
    location: region,
    area: getArea(region),
    lat,
    lng,
    desc,
    level,
    featured: FEATURED[level].includes(name),
  };
}

